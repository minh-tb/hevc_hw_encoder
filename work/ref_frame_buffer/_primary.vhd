        CHROMA_WORDS    : vl_notype;
        FRAME_WORDS     : vl_notype;
        CB_OFFSET       : vl_notype;
        CR_OFFSET       : vl_notype;
        SLOT_STRIDE     : vl_notype;
        PX_EXT_Y        : vl_notype;
        PX_EXT_C        : vl_notype
