        axi_arready     : in     vl_logic;
        axi_araddr      : out    vl_logic_vector;
        axi_arlen       : out    vl_logic_vector(7 downto 0);
        axi_arsize      : out    vl_logic_vector(2 downto 0);
        axi_arburst     : out    vl_logic_vector(1 downto 0);
        axi_rvalid      : in     vl_logic;
        axi_rready      : out    vl_logic;
        axi_rdata       : in     vl_logic_vector;
        axi_rlast       : in     vl_logic
    );
    attribute mti_svvh_generic_type : integer;
    attribute mti_svvh_generic_type of PIXEL_WIDTH : constant is 1;
    attribute mti_svvh_generic_type of BLK_SIZE : constant is 1;
    attribute mti_svvh_generic_type of BLK_EXT_Y : constant is 3;
    attribute mti_svvh_generic_type of BLK_EXT_C : constant is 3;
    attribute mti_svvh_generic_type of FRAME_W_Y : constant is 1;
    attribute mti_svvh_generic_type of FRAME_H_Y : constant is 1;
    attribute mti_svvh_generic_type of FRAME_W_C : constant is 1;
    attribute mti_svvh_generic_type of FRAME_H_C : constant is 1;
    attribute mti_svvh_generic_type of AXI_DW : constant is 1;
    attribute mti_svvh_generic_type of AXI_AW : constant is 1;
    attribute mti_svvh_generic_type of LUMA_SAMPLES : constant is 3;
    attribute mti_svvh_generic_type of CHROMA_SAMPLES : constant is 3;
    attribute mti_svvh_generic_type of LUMA_WORDS : constant is 3;
    attribute mti_svvh_generic_type of CHROMA_WORDS : constant is 3;
    attribute mti_svvh_generic_type of FRAME_WORDS : constant is 3;
    attribute mti_svvh_generic_type of CB_OFFSET : constant is 3;
    attribute mti_svvh_generic_type of CR_OFFSET : constant is 3;
    attribute mti_svvh_generic_type of SLOT_STRIDE : constant is 3;
    attribute mti_svvh_generic_type of PX_EXT_Y : constant is 3;
    attribute mti_svvh_generic_type of PX_EXT_C : constant is 3;
end ref_frame_buffer;
