    port(
        clk             : in     vl_logic;
        rst_n           : in     vl_logic;
        ref_req_valid   : in     vl_logic;
        ref_req_ready   : out    vl_logic;
        ref_req_comp    : in     vl_logic_vector(1 downto 0);
        ref_req_slot    : in     vl_logic_vector(2 downto 0);
